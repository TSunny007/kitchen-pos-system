-- Card payments taken through the Square Point of Sale app.
--
-- Square is optional: a deployment that never configures it keeps every order
-- at payment_status 'untracked', which is exactly how orders behaved before
-- this migration (the kitchen sees them straight away).

-- 1. Order payment status
--
--   untracked - payment isn't recorded by the app (Square off, or a legacy row)
--   awaiting  - handed to Square, not confirmed yet; hidden from the kitchen
--   paid      - confirmed with Square; at least one row in public.payments
--   cash      - marked paid in cash at the terminal
--
-- A voided order keeps its payment_status and moves to status 'cancelled'.
alter table public.orders
  add column payment_status text not null default 'untracked'
    check (payment_status in ('untracked', 'awaiting', 'paid', 'cash')),
  -- Square's transaction id from the POS callback, saved before verifying it,
  -- so a verification that fails part-way can be retried without the callback.
  add column payment_reference text;

-- 2. Payments
--
-- Written only by the square-verify-payment Edge Function (service role),
-- never by the browser, so a row here always means Square confirmed it.
-- Amounts are integers in the currency's minor unit (cents for USD, yen for
-- JPY), exactly as Square reports them.
create table public.payments (
  id                   bigint generated by default as identity primary key,
  order_id             bigint not null references public.orders(id) on delete cascade,
  provider             text not null default 'square' check (provider in ('square')),
  provider_payment_id  text not null,
  provider_order_id    text,
  base_amount_minor    bigint not null check (base_amount_minor >= 0),
  tip_amount_minor     bigint not null default 0 check (tip_amount_minor >= 0),
  total_amount_minor   bigint not null check (total_amount_minor >= 0),
  currency             text not null check (currency ~ '^[A-Z]{3}$'),
  status               text not null,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  -- Recording the same Square payment twice (a retried callback) is a no-op,
  -- and one payment can't be attached to two orders.
  unique (provider, provider_payment_id)
);

create index payments_order_id_idx on public.payments (order_id);

-- 3. 'paid' must be backed by a payment row
--
-- The orders update policy lets any signed-in user change any column, so
-- without this a client could mark an order paid without Square ever seeing
-- it. 'cash' stays client-settable on purpose: that's the manual fallback.
create function public.enforce_paid_has_payment()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.payment_status = 'paid'
     and (tg_op = 'INSERT' or old.payment_status is distinct from 'paid')
     and not exists (select 1 from public.payments p where p.order_id = new.id) then
    raise exception 'order % cannot be marked paid without a recorded payment', new.id
      using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

create trigger orders_paid_requires_payment
  before insert or update of payment_status on public.orders
  for each row execute function public.enforce_paid_has_payment();

-- 4. RLS
--
-- Signed-in staff can read payments. There are deliberately no insert, update
-- or delete policies: only the Edge Function, using the service role (which
-- bypasses RLS), writes them.
alter table public.payments enable row level security;

create policy "Allow authenticated users to read payments"
  on public.payments for select
  to authenticated
  using (true);
