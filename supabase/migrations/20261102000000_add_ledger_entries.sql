-- Balance sheet: a ledger for money the order data can't tell us about, and a
-- per-campaign rollup that sets it beside revenue.
--
-- Revenue is not stored here - it is derived from orders (see campaign_balance
-- below). This table holds the rest: groceries and other costs, and additions
-- like tips. One signed column rather than a kind flag plus a magnitude, so the
-- sign and the label can never disagree and "net" is just a sum:
--   amount < 0   an expense
--   amount > 0   an addition (tips, donations)

create table public.ledger_entries (
  id                bigint generated by default as identity primary key,
  -- NULL = not tied to a campaign (a bulk grocery run, say). It still counts
  -- toward the organisation's total; it just belongs to no single campaign's
  -- net. SET NULL rather than CASCADE so that deleting a campaign can never
  -- silently delete financial records - the money moves to "not tied" instead,
  -- the same way orders.campaign_id behaves.
  campaign_id       bigint references public.campaigns(id) on delete set null,
  label             text not null,              -- 'Costco run', 'Tips'
  amount            numeric(10,2) not null,
  created_at        timestamptz not null default now(),
  constraint ledger_entries_amount_nonzero check (amount <> 0),
  constraint ledger_entries_label_not_blank check (btrim(label) <> '')
);

create index ledger_entries_campaign_id_idx on public.ledger_entries (campaign_id);

alter table public.ledger_entries enable row level security;

create policy "Allow authenticated users to read ledger_entries"
  on public.ledger_entries for select
  to authenticated
  using (true);

create policy "Allow authenticated users to insert ledger_entries"
  on public.ledger_entries for insert
  to authenticated
  with check (true);

create policy "Allow authenticated users to update ledger_entries"
  on public.ledger_entries for update
  to authenticated
  using (true)
  with check (true);

create policy "Allow authenticated users to delete ledger_entries"
  on public.ledger_entries for delete
  to authenticated
  using (true);

-- One row per campaign, plus one with campaign_id NULL when orders or ledger
-- entries exist that belong to no campaign. Summing every row is the
-- organisation's total - there is no org table, because there is one
-- deployment per organisation.
--
-- Revenue counts completed orders only, and within them every item that was not
-- cancelled, priced the way lineTotal() prices a cart line. It is computed from
-- order_items rather than read from orders.subtotal because nothing
-- recalculates the subtotal when an item is cancelled, and
-- recalculateOrderSubtotal() counts cancelled items; a stored figure would
-- overstate revenue for any order that had one.
--
-- This is a view, not client-side arithmetic, because PostgREST caps a response
-- at 1000 rows (max_rows in config.toml) and truncates silently: summing every
-- order item across every campaign in the browser would drop the tail of the
-- data and still render a confident total.
--
-- security_invoker makes the view run with the caller's privileges, so the RLS
-- policies on the underlying tables apply. Without it a view runs as its owner
-- and would hand these totals to the anon key.
create view public.campaign_balance
with (security_invoker = true) as
with revenue as (
  select
    o.campaign_id,
    sum((i.base_price + coalesce(m.delta, 0)) * oi.quantity) as revenue
  from public.orders o
  join public.order_items oi
    on oi.order_id = o.id
   and oi.status <> 'cancelled'
  join public.items i on i.id = oi.item_id
  left join lateral (
    select sum(price_delta) as delta
    from public.order_item_modifiers
    where order_item_id = oi.id
  ) m on true
  where o.status = 'completed'
  group by o.campaign_id
),
ledger as (
  select
    campaign_id,
    coalesce(sum(amount) filter (where amount < 0), 0) as expenses,
    coalesce(sum(amount) filter (where amount > 0), 0) as additions
  from public.ledger_entries
  group by campaign_id
)
select
  k.campaign_id,
  coalesce(r.revenue, 0)   as revenue,
  coalesce(l.expenses, 0)  as expenses,   -- zero or negative
  coalesce(l.additions, 0) as additions   -- zero or positive
from (
  -- UNION treats NULLs as equal, so the "not tied to a campaign" key appears
  -- once however many of the sources have it.
  select id as campaign_id from public.campaigns
  union
  select campaign_id from revenue
  union
  select campaign_id from ledger
) k
-- IS NOT DISTINCT FROM so the NULL key joins to its own totals; a plain = would
-- never match it. Legal here because these are LEFT joins (a FULL join needs a
-- hashable or mergeable condition, which this is not).
left join revenue r on r.campaign_id is not distinct from k.campaign_id
left join ledger  l on l.campaign_id is not distinct from k.campaign_id;
